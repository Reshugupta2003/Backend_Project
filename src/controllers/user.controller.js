import { asyncHandler } from "../utils/asyncHandler.js";
import {ApiError} from "../utils/apiError.js";
import {User} from "../models/user.model.js";
import {uploadOnCloudinary} from "../utils/cloudinary.js";
import{ ApiResponce } from "../utils/ApiResponce.js";
import jwt from "jsonwebtoken";

//common pattern

const generateAccessAndRefreshTokens = async(userId) => {
   try {
       const user = await User.findById(userId); // similar like - mongoose.model("User", new Schema({}, {},...)).findById(userId);
 
       const accessToken = user.generateAccessToken();
       const refreshToken = user.generateRefreshToken();
       user.refreshToken = refreshToken;
        await user.save({ validateBeforeSave: false }); // not able to skip pre middleware
    //    console.log(user);
       return {accessToken, refreshToken};
   } catch (error) {
    throw new ApiError(500, error);
   }
}
  
  //1. registerUser/ signupUser
  const registerUser = asyncHandler( async (req, res) => {
    /* 
    1. get user datails from frontend
    2. validate user datails
    3. check if user already exists - username, email
    4. check avtar, image
    5. upload image, avtar to cloudinary
    6. create user objeect
    7. remove password and refresh token from response
    8. check if user is created successfully
    9. send response to frontend (if error send error response) 
     */

    // if data comes from json or form then we can use req.body to get the data otherwise we can use req.query or req.params to get the data from url.

    //when i send data through postman in json format it's doesn't matter the order of sending data & we also miss some data still is works
    // 1.
    const {fullname, username, email, password } = req.body; // object destructuring

     // if you want to see the result of this line use postman.
   
     // 2. 
    if(
        [fullname, username, email, password].some((field) => 
            field ?. trim() === "")
    ){
       throw new ApiError(400, "All fields are required"); //400 is bad request error - bcoz of user input invaild, extra space, empty string
    }

    //3.  mongoDB have multiple query operator like or, ex - $and, $not, $lt, $lts, $gt, $gte, $ne, $nor
    // if you remove await postman gives 409 error.
    const existedUser = await User.findOne({
        $or: [{ username }, { email }]
    })
    // findOne send full object as store on mongoDB of the user if exist 
    if(existedUser){
       throw new ApiError(409, "User already exists with this username or email");
    }

    // 4. 
    const avatarLocalPath = req.files?.avatar?.[0]?.path; // if user send avatar image then we can get the path of the image from req.files.avatar[0].path
    //const coverImageLocalPath = req.files?.coverImage?.[0]?.path; // this will tell use each file store in a array 
    let coverImageLocalPath;
    if (req.files && Array.isArray(req.files.coverImage) && req.files.coverImage.length > 0) {
        coverImageLocalPath = req.files.coverImage[0].path
    }
  
    if(!avatarLocalPath){
        throw new ApiError(400, "Avatar image is required");
    }
    //5. 
    const avatar = await uploadOnCloudinary(avatarLocalPath);
    const coverImage = (await uploadOnCloudinary(coverImageLocalPath)) || " " ; // if coverImage null

   
    if(!avatar){
        throw new ApiError(500, "Failed to upload avatar or cover image");
    }

   
    // 6.
    const user = await User.create({
        fullName : fullname,
        avatar: avatar.url,
        coverImage: coverImage.url || "",
        email :email,
        password : password,
        userName: username.toLowerCase().trim(), // Key must be same as user.model.js
    })
    const createdUser = await User.findById(user._id).select("-password -refreshToken"); // we can use select method to remove password and refresh token from response and _id is automatically generated by mongodb.

    if(!createdUser){
        throw new ApiError(500, "Something went wrong while registering user");
    }

    return res.status(201).json(
        new ApiResponce(200, createdUser, "User register successfully")
    );
  })


  //2. loginUser
  const loginUser = asyncHandler(async (req, res) => {
    /* 
    1. take data from req.body
    2. username or email
    3. find the user
    4. password check
    5. send refresh, access token using cookies to user
     */

    const {userName, email, password} = req.body;

    if(!userName && !email){
        throw new ApiError(400, "username or email required");
    }
    const user = await User.findOne({
        $or : [{userName}, {email}]
    })

    if(!user){
        throw new ApiError(404, "User doesn't exist");
    }
    // isPasswordCorrect is a own build method in user.model file
    // we will never the password to user while they requested for login/signup
    const isPasswordValid = await user.isPasswordCorrect(password);

    if(!isPasswordValid){
        throw new ApiError(401, "User credential is invalid");
    }
    // generate it every login
    const {accessToken, refreshToken} = await 
    generateAccessAndRefreshTokens(user._id);

    const loggedInUser = await User.findById(user._id).
    select("-password -refreshToken"); // it ensured that password and refreshToken wouldn't send to user.

     const options = {    // it is ensure that 
        httpOnly: true,
        secure: true
    }

    // set refresh & access token in cookies using cookies-parser library
    return res
    .status(200)
    .cookie("accessToken", accessToken, options) // this tell to broswer to store accessToken in cookies and it is httpOnly so user can't access it from frontend.
    .cookie("refreshToken", refreshToken, options)
    .json(
        new ApiResponce(
            200, 
            {
                user: loggedInUser, accessToken, refreshToken // send token here also, if in case user want to save it on localStorage
            },
            "User logged In Successfully"
        )
    )
  })

  //3. logoutUser
  const logoutUser = asyncHandler( async (req, res) => {
     /*
     1. before calling it route called verifyJWT middleware because request doesn't have 
        id/email/username of user to logout it so this middleware add req.user.
     2. now we will set refreshToken undefine.
     */
 
      await User.findByIdAndUpdate(
        req.user._id,
        {
            $unset : {
                refreshToken : 1 // it will remove refreshToken from user object in mongoDB
            }
        },
        {
            new : true
        }
      )
      const options = {
        httpOnly : true,
         secure : true
      }

      return res.status(200)
      .clearCookie("accessToken", options) // it will remove accessToken from broswer cookies 
      .clearCookie("refreshToken", options)
      .json(new ApiResponce(200, {}, "User logged Out"))
  })

  // 4. refresh Access Token
  const refreshAccessToken = asyncHandler(async (req, res) => {
      const incomingRefreshToken = req.cookies.refreshToken || req.body.refreshToken;

      if(!incomingRefreshToken){
        throw new ApiError(401, "Unauthorized request, refresh token is required");
      }
      
      try {
        const decodeToken = jwt.verify(incomingRefreshToken, process.env.REFRESH_TOKEN_SECRET);
  
        const user = await User.findById(decodeToken?._id);
  
        if(!user || user.refreshToken !== incomingRefreshToken){
          throw new ApiError(401, "Unauthorized request, refresh token is invalid");
        }
  
        const options = {
          httpOnly : true,
          secure : true  // tells to broswer that cookies should be sent only over https and http://localhost for testing purpose.
        }
  
         const {accessToken, newRefreshToken} = await generateAccessAndRefreshTokens(user._id);
  
        return res.status(200)
          .cookie("accessToken", accessToken, options)
          .cookie("refreshToken", newRefreshToken, options)
          .json(
              new ApiResponce(
                  200,
                  {
                     accessToken: accessToken, refreshToken: newRefreshToken
                  },
                  "Access token refreshed successfully"
              )
          )
      } catch (error) {
         throw new ApiError(401, error.message || "Unauthorized request, refresh token is invalid");
      }
  })

  
export {
    registerUser,
    loginUser,
    logoutUser,
    refreshAccessToken
};
